<?php
require __DIR__ . '/config/config.php';

// Remove everything from the session, expire the session cookie, then destroy it.
$_SESSION = [];
if (ini_get('session.use_cookies')) {
    $p = session_get_cookie_params();
    setcookie(session_name(), '', [
        'expires' => time() - 42000,
        'path' => $p['path'],
        'domain' => $p['domain'],
        'secure' => $p['secure'],
        'httponly' => $p['httponly'],
        'samesite' => $p['samesite'] ?? 'Lax',
    ]);
}
session_destroy();

header('Location: ' . BASE_URL . '/index.php?view=login');
exit;
